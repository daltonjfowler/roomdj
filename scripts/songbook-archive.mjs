// npm run songbook:archive: every song the live checker already passed (KV verdict:v<PROMPT_VERSION>:<id>
// for an iTunes id) goes on the songbook shelves by genre (Dalton, 2026-10-30: "we have SO MANY
// approved but only list like 15 under pop"). READ-ONLY on the live site: lists and reads the verdict
// keys with Wrangler's login, then looks each id up on iTunes (150 a call) for its title, genre,
// year and cover. Writes src/songbook-archive-data.js; deploy to ship it. Run it again now and then:
// the archive grows every day. Kept: ✓ Checked by the same rule as search (readyToPlay), never
// explicit and the rest of src/songbook.js shelfWorthy. Lookups are cached in node_modules/.cache/songbook-archive.json.
//   node scripts/songbook-archive.mjs [--fresh]

import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PROMPT_VERSION, banKey, readVerdict, readyToPlay } from '../shared/filter.js';
import { parseItunes, toSong } from '../shared/itunes.js';
import { archiveShelves, shelfWorthy } from '../src/songbook.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'src', 'songbook-archive-data.js');
const CACHE = join(root, 'node_modules', '.cache', 'songbook-archive.json');
const TMP = join(root, 'node_modules', '.cache', 'songbook-archive-keys.json');
const WRANGLER = join(root, 'node_modules', 'wrangler', 'bin', 'wrangler.js');
const GAP_MS = 3200;
const LOOKUP_IDS = 150;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const cache = process.argv.includes('--fresh') ? {} : JSON.parse(await readFile(CACHE, 'utf8').catch(() => '{}'));
await mkdir(dirname(CACHE), { recursive: true });

function kv(...args) {
  const r = spawnSync(process.execPath, [WRANGLER, 'kv', ...args, '--binding', 'CLASS_KV', '--remote'], { cwd: root, encoding: 'utf8', maxBuffer: 64 << 20 });
  if (r.status !== 0) throw new Error(`wrangler kv ${args.slice(0, 2).join(' ')} failed: ${r.stderr.slice(-400)}`);
  return JSON.parse(r.stdout.slice(r.stdout.search(/[[{]/)));
}

// 1. The verdicts kept per iTunes id (a number), read 100 at a time.
const prefix = `verdict:v${PROMPT_VERSION}:`;
const keys = kv('key', 'list', '--prefix', prefix).map((k) => k.name).filter((n) => /^\d+$/.test(n.slice(prefix.length)));
console.log(`${keys.length} songs checked under prompt v${PROMPT_VERSION}`);
const verdicts = new Map();
for (let i = 0; i < keys.length; i += 100) {
  await writeFile(TMP, JSON.stringify(keys.slice(i, i + 100)));
  for (const [k, v] of Object.entries(kv('bulk', 'get', TMP))) {
    const parsed = readVerdict(typeof v === 'string' ? JSON.parse(v) : v);
    if (parsed?.verdict === 'ok') verdicts.set(k.slice(prefix.length), parsed);
  }
}
console.log(`${verdicts.size} of them OK`);

// 2. Their details from iTunes.
async function lookup(ids) {
  const todo = ids.filter((id) => !(id in cache));
  for (let i = 0; i < todo.length; i += LOOKUP_IDS) {
    const batch = todo.slice(i, i + LOOKUP_IDS);
    for (let tries = 0; ; tries++) {
      await sleep(GAP_MS);
      const r = await fetch(`https://itunes.apple.com/lookup?id=${batch.join(',')}&entity=song&country=US`).catch(() => null);
      if (r?.ok) {
        const found = new Map((parseItunes(await r.text()) ?? []).map((x) => [String(x.trackId), x]));
        for (const id of batch) cache[id] = found.get(id) ?? null;
        break;
      }
      if (tries >= 3) throw new Error(`iTunes keeps refusing lookups (${r?.status ?? 'down'})`);
      console.log(`  iTunes ${r?.status ?? 'down'}, waiting a minute`);
      await sleep(60_000);
    }
    await writeFile(CACHE, JSON.stringify(cache));
  }
}
await lookup([...verdicts.keys()]);

// 3. The songs a shelf may show, one per song (banKey), newest first.
const songs = [];
const seen = new Set();
const left = { gone: 0, notReady: 0, notForShelf: 0, noShelf: 0 };
for (const [id, v] of verdicts) {
  const song = toSong(cache[id]);
  if (!song) { left.gone++; continue; }
  if (!readyToPlay(song, v)) { left.notReady++; continue; }
  if (!shelfWorthy(song)) { left.notForShelf++; continue; }
  const shelves = archiveShelves(song, { instrumental: v.instrumental === true || v.lyrics === 'instrumental' });
  if (!shelves.length) { left.noShelf++; continue; }
  const key = banKey(song);
  if (seen.has(key)) continue;
  seen.add(key);
  songs.push({ ...song, shelves, ...(v.instrumental === true || v.lyrics === 'instrumental' ? { instrumental: true } : {}) });
}
songs.sort((a, b) => (b.year || 0) - (a.year || 0) || a.title.localeCompare(b.title));

const made = new Date().toISOString().slice(0, 10);
await writeFile(OUT, `// Generated by \`npm run songbook:archive\` (scripts/songbook-archive.mjs) on ${made}. Do not edit by hand.
// Songs the live checker passed under prompt v${PROMPT_VERSION}, by shelf (src/songbook.js).
export const ARCHIVE_MADE = '${made}';
export const ARCHIVE_VERSION = ${PROMPT_VERSION};
export const ARCHIVE_SONGS = ${JSON.stringify(songs, null, 0).replace(/},{/g, '},\n{')};
`);
const per = {};
for (const s of songs) for (const sh of s.shelves) per[sh] = (per[sh] ?? 0) + 1;
console.log(`${songs.length} songs written to src/songbook-archive-data.js`, per);
console.log('left out:', left);
